#!/usr/bin/env python3
"""
Generates plain JPA entity classes (no Lombok) from compact .spec files.

Why: the PSP modules avoid Lombok so they compile and read the same in
any IDE, but hand-writing getters/setters for ~60 entities is error-prone.
Specs live next to this script; output goes under src/main/java.

Spec format (one entity per block):

  @entity <ClassName> <table_name> <package>
  @doc <one line of class javadoc>          (repeatable)
  @import <fully.qualified.Type>            (repeatable)
  @index <name> <col1,col2> [unique]        (repeatable)
  @immutable                                (all columns updatable=false; append-only tables also blocked by DB triggers)
  <fieldName> <JavaType> [col=<db_col>] [len=N] [notnull] [unique] [enum] [text] [default=<java expr>] [encrypted] [updatable=false] [precision=P scale=S]
  @created <fieldName>                      (LocalDateTime set in @PrePersist)
  @updated <fieldName>                      (LocalDateTime set in @PrePersist and @PreUpdate)
  @version                                  (optimistic locking column 'version')

Usage: gen_entities.py <spec files...> --out <src/main/java>
"""
import os
import re
import sys


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def cap(name):
    return name[0].upper() + name[1:]


class Field:
    def __init__(self, name, jtype, opts):
        self.name = name
        self.jtype = jtype
        self.opts = opts

    def opt(self, key, default=None):
        for o in self.opts:
            if o == key:
                return True
            if o.startswith(key + '='):
                return o.split('=', 1)[1]
        return default


def parse(path):
    entities = []
    cur = None
    with open(path) as f:
        for raw in f:
            line = raw.rstrip('\n')
            if not line.strip() or line.strip().startswith('#'):
                continue
            parts = line.split()
            head = parts[0]
            if head == '@entity':
                cur = dict(name=parts[1], table=parts[2], package=parts[3], docs=[], imports=[],
                           indexes=[], fields=[], created=None, updated=None, version=False, immutable=False)
                entities.append(cur)
            elif head == '@doc':
                cur['docs'].append(line.split(None, 1)[1] if len(parts) > 1 else '')
            elif head == '@import':
                cur['imports'].append(parts[1])
            elif head == '@index':
                cur['indexes'].append((parts[1], parts[2], len(parts) > 3 and parts[3] == 'unique'))
            elif head == '@created':
                cur['created'] = parts[1]
            elif head == '@updated':
                cur['updated'] = parts[1]
            elif head == '@version':
                cur['version'] = True
            elif head == '@immutable':
                cur['immutable'] = True
            else:
                cur['fields'].append(Field(parts[0], parts[1], parts[2:]))
    return entities


def render(e):
    out = []
    out.append(f"package {e['package']};\n")
    imports = {
        'jakarta.persistence.*',
    }
    needs_time = any(f.jtype in ('LocalDateTime',) for f in e['fields']) or e['created'] or e['updated']
    if needs_time:
        imports.add('java.time.LocalDateTime')
    if any(f.jtype == 'LocalDate' for f in e['fields']):
        imports.add('java.time.LocalDate')
    if any(f.jtype == 'BigDecimal' for f in e['fields']):
        imports.add('java.math.BigDecimal')
    if any(f.opt('encrypted') for f in e['fields']):
        imports.add('zw.co.payport.gateway.psp.platform.crypto.EncryptedStringConverter')
    for i in e['imports']:
        imports.add(i)
    for i in sorted(imports):
        out.append(f"import {i};")
    out.append("")
    out.append("/**")
    out.append(" * GENERATED by tools/codegen/gen_entities.py from " + e['spec'] + " -- edit the spec, not this file.")
    for d in e['docs']:
        out.append(" * " + d)
    out.append(" */")
    out.append("@Entity")
    idx = []
    uniq = []
    for name, cols, unique in e['indexes']:
        idx.append(f'@Index(name = "{name}", columnList = "{cols}"' + (', unique = true' if unique else '') + ')')
    if idx:
        out.append(f'@Table(name = "{e["table"]}", indexes = {{')
        out.append(",\n".join("        " + i for i in idx))
        out.append("})")
    else:
        out.append(f'@Table(name = "{e["table"]}")')
    out.append(f"public class {e['name']} {{\n")

    out.append("    @Id")
    out.append("    @GeneratedValue(strategy = GenerationType.IDENTITY)")
    out.append("    private Long id;\n")

    for f in e['fields']:
        ann = []
        col = f.opt('col') or snake(f.name)
        colargs = [f'name = "{col}"']
        if f.opt('notnull'):
            colargs.append('nullable = false')
        if f.opt('unique'):
            colargs.append('unique = true')
        if f.opt('len'):
            colargs.append(f'length = {f.opt("len")}')
        if f.opt('updatable') == 'false' or e['immutable']:
            colargs.append('updatable = false')
        if f.opt('precision'):
            colargs.append(f'precision = {f.opt("precision")}')
            colargs.append(f'scale = {f.opt("scale")}')
        if f.opt('text'):
            colargs.append('columnDefinition = "TEXT"')
        if f.opt('enum'):
            ann.append('@Enumerated(EnumType.STRING)')
        if f.opt('encrypted'):
            ann.append('@Convert(converter = EncryptedStringConverter.class)')
        ann.append('@Column(' + ', '.join(colargs) + ')')
        for a in ann:
            out.append("    " + a)
        default = f.opt('default')
        out.append(f"    private {f.jtype} {f.name}" + (f" = {default}" if default else "") + ";\n")

    if e['created']:
        out.append(f'    @Column(name = "{snake(e["created"])}", nullable = false, updatable = false)')
        out.append(f"    private LocalDateTime {e['created']};\n")
    if e['updated']:
        out.append(f'    @Column(name = "{snake(e["updated"])}", nullable = false)')
        out.append(f"    private LocalDateTime {e['updated']};\n")
    if e['version']:
        out.append("    @Version")
        out.append('    @Column(name = "version", nullable = false)')
        out.append("    private Long version;\n")

    if e['created'] or e['updated']:
        out.append("    @PrePersist")
        out.append("    protected void onCreate() {")
        out.append("        LocalDateTime now = LocalDateTime.now();")
        if e['created']:
            out.append(f"        if ({e['created']} == null) {e['created']} = now;")
        if e['updated']:
            out.append(f"        {e['updated']} = now;")
        out.append("    }\n")
        if e['updated']:
            out.append("    @PreUpdate")
            out.append("    protected void onUpdate() {")
            out.append(f"        {e['updated']} = LocalDateTime.now();")
            out.append("    }\n")

    all_fields = [('Long', 'id')] + [(f.jtype, f.name) for f in e['fields']]
    if e['created']:
        all_fields.append(('LocalDateTime', e['created']))
    if e['updated']:
        all_fields.append(('LocalDateTime', e['updated']))
    if e['version']:
        all_fields.append(('Long', 'version'))
    for jtype, name in all_fields:
        getter = ('is' if jtype == 'boolean' else 'get') + cap(name)
        out.append(f"    public {jtype} {getter}() {{ return {name}; }}")
        if name != 'version':
            out.append(f"    public void set{cap(name)}({jtype} {name}) {{ this.{name} = {name}; }}")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    out_root = args[args.index('--out') + 1]
    specs = [a for a in args if a.endswith('.spec')]
    n = 0
    for spec in specs:
        for e in parse(spec):
            e['spec'] = os.path.basename(spec)
            d = os.path.join(out_root, *e['package'].split('.'))
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, e['name'] + '.java'), 'w') as fh:
                fh.write(render(e))
            n += 1
    print(f"generated {n} entities")


if __name__ == '__main__':
    main()
