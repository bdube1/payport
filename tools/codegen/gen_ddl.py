#!/usr/bin/env python3
"""
Generates MySQL 8 CREATE TABLE statements from the same .spec files that
generate the JPA entities, so schema and entities cannot drift.

Usage: gen_ddl.py <out.sql> <title> <spec files...>
"""
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from gen_entities import parse, snake  # noqa: E402

TYPES = {
    'String': None, 'long': 'BIGINT', 'Long': 'BIGINT', 'int': 'INT', 'Integer': 'INT',
    'boolean': 'BOOLEAN', 'Boolean': 'BOOLEAN', 'LocalDateTime': 'DATETIME(6)', 'LocalDate': 'DATE',
    'BigDecimal': None,
}
PRIMITIVES = {'long', 'int', 'boolean'}


def column(f):
    col = f.opt('col') or snake(f.name)
    t = f.jtype
    if f.opt('enum') or t == 'String':
        sql = 'TEXT' if f.opt('text') else f"VARCHAR({f.opt('len') or 255})"
    elif t == 'BigDecimal':
        sql = f"DECIMAL({f.opt('precision') or 19},{f.opt('scale') or 4})"
    elif t in TYPES:
        sql = TYPES[t]
    else:  # enum types declared by class name
        sql = f"VARCHAR({f.opt('len') or 40})"
    notnull = f.opt('notnull') or t in PRIMITIVES
    parts = [f"    {col:<28} {sql}"]
    if notnull:
        parts.append('NOT NULL')
    d = f.opt('default')
    if d is not None:
        if d.startswith('"'):
            parts.append(f"DEFAULT '{d.strip(chr(34))}'")
        elif d in ('true', 'false'):
            parts.append(f"DEFAULT {d.upper()}")
        elif d.lstrip('-').isdigit():
            parts.append(f"DEFAULT {d}")
    elif t in ('long', 'int'):
        parts.append('DEFAULT 0')
    elif t == 'boolean':
        parts.append('DEFAULT FALSE')
    return ' '.join(parts)


def table(e):
    lines = ["    id                           BIGINT AUTO_INCREMENT PRIMARY KEY"]
    uniques = []
    for f in e['fields']:
        lines.append(column(f))
        if f.opt('unique'):
            uniques.append(snake(f.name) if not f.opt('col') else f.opt('col'))
    if e['created']:
        lines.append(f"    {snake(e['created']):<28} DATETIME(6) NOT NULL")
    if e['updated']:
        lines.append(f"    {snake(e['updated']):<28} DATETIME(6) NOT NULL")
    if e['version']:
        lines.append(f"    {'version':<28} BIGINT NOT NULL DEFAULT 0")
    for u in uniques:
        lines.append(f"    CONSTRAINT uq_{e['table'][4:] if e['table'].startswith('psp_') else e['table']}_{u} UNIQUE ({u})")
    for name, cols, unique in e['indexes']:
        lines.append(f"    {'CONSTRAINT ' + name + ' UNIQUE' if unique else 'INDEX ' + name} ({cols})")
    doc = '\n'.join('-- ' + d for d in e['docs'])
    return f"{doc}\nCREATE TABLE {e['table']} (\n" + ',\n'.join(lines) + "\n);\n"


def main():
    out, title, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    parts = [f"-- =====================================================================\n-- {title}\n-- GENERATED by tools/codegen/gen_ddl.py from {', '.join(s.split('/')[-1] for s in specs)}\n-- (same specs as the JPA entities). Edit the spec, regenerate, never hand-edit.\n-- =====================================================================\n"]
    for spec in specs:
        for e in parse(spec):
            parts.append(table(e))
    open(out, 'w').write('\n'.join(parts))
    print('wrote', out)


if __name__ == '__main__':
    main()
