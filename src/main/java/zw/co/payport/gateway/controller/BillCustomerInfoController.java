package zw.co.payport.gateway.controller;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import zw.co.payport.gateway.model.response.ApiResponse;
import zw.co.payport.gateway.service.adaptor.esolutions.bulawayo.BulawayoBillAdaptor;
import zw.co.payport.gateway.service.adaptor.esolutions.moonlight.MoonlightAdaptor;
import zw.co.payport.gateway.service.adaptor.esolutions.nyaradzo.NyaradzoAdaptor;
import zw.co.payport.gateway.service.adaptor.esolutions.zesa.ZesaTokenAdaptor;
import zw.co.payport.gateway.service.adaptor.esolutions.zol.ZolPaymentAdaptor;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;

/**
 * Customer Info Controller
 *
 * NOTE: This is a READ-ONLY lookup. No transaction is created, no money is deducted.
 * A unique request ID is generated for tracing purposes only, NOT as a transaction reference.
 * The actual transaction reference (Payport reference) is generated by the client (mobile/web/USSD)
 * during the /initiate call.
 *
 * Endpoints:
 *   POST /api/v1/bills/customer-info
 *
 * Request body:
 *   {
 *     "merchantCode":   "ZESA" | "BULAWAYO" | "ZOL" | "NYARADZO" | "MOONLIGHT",
 *     "accountNumber":  "48205673603",      // meter number, account, policy number
 *     "currencyCode":   "USD",              // required for ZESA (affects meter currency check)
 *     "sourcePhone":    "+263771234567"     // optional, for life assurance
 *   }
 */
@Slf4j
@RestController
@RequestMapping("/api/v1/bills")
@RequiredArgsConstructor
public class BillCustomerInfoController {

    private final ZesaTokenAdaptor    zesaAdaptor;
    private final BulawayoBillAdaptor bulawayoAdaptor;
    private final ZolPaymentAdaptor   zolAdaptor;
    private final NyaradzoAdaptor     nyaradzoAdaptor;
    private final MoonlightAdaptor    moonlightAdaptor;

    @PostMapping("/customer-info")
    public ResponseEntity<ApiResponse<Map<String, Object>>> getCustomerInfo(
            @RequestBody Map<String, String> req) {

        // Generate a tracing ID for this request (NOT a transaction reference)
        String traceId = "TRACE-" + UUID.randomUUID().toString().substring(0, 8);

        try {
            String merchantCode  = upper(req.get("merchantCode"));
            String accountNumber = req.get("accountNumber");
            String currencyCode  = req.getOrDefault("currencyCode", "USD");
            String sourcePhone   = req.get("sourcePhone");

            if (merchantCode == null || merchantCode.isBlank()) {
                return badRequest("merchantCode is required", traceId);
            }
            if (accountNumber == null || accountNumber.isBlank()) {
                return badRequest("accountNumber is required", traceId);
            }

            Map<String, Object> result;

            switch (merchantCode) {
                case "ZESA": {
                    // Validate meter locally first (per UAT test 16)
                    String meterError = ZesaTokenAdaptor.validateMeter(accountNumber);
                    if (meterError != null) {
                        result = Map.of("error", meterError);
                        break;
                    }

                    ZesaTokenAdaptor.ZesaCustomerInfo info =
                            zesaAdaptor.getCustomerInfo(accountNumber.trim(), currencyCode);

                    // Use LinkedHashMap to preserve order for ZESA response
                    result = new LinkedHashMap<>();
                    result.put("customerName",    nullSafe(info.customerName()));
                    result.put("customerAddress", nullSafe(info.customerAddress()));
                    result.put("meterNumber",     info.meterNumber());
                    result.put("meterCurrency",   nullSafe(info.meterCurrency()));
                    result.put("merchantCode",    "ZESA");
                    break;
                }
                case "BULAWAYO": {
                    BulawayoBillAdaptor.BulawayoCustomerInfo info =
                            bulawayoAdaptor.getCustomerInfo(accountNumber.trim(), currencyCode);
                    result = new LinkedHashMap<>();
                    result.put("customerName",  nullSafe(info.customerName()));
                    result.put("accountNumber", info.accountNumber());
                    result.put("merchantCode",  "BULAWAYO");
                    break;
                }
                case "ZOL": {
                    ZolPaymentAdaptor.ZolCustomerInfo info =
                            zolAdaptor.getCustomerInfo(accountNumber.trim());
                    result = new LinkedHashMap<>();
                    result.put("customerName",  nullSafe(info.customerName()));
                    result.put("accountNumber", info.accountNumber());
                    result.put("merchantCode",  "ZOL");
                    break;
                }
                case "NYARADZO": {
                    NyaradzoAdaptor.NyaradzoCustomerInfo info =
                            nyaradzoAdaptor.getCustomerInfo(accountNumber.trim(), sourcePhone);
                    result = new LinkedHashMap<>();
                    result.put("holderName",          nullSafe(info.holderName()));
                    result.put("policyNumber",        info.policyNumber());
                    result.put("balanceCents",        info.balanceCents());
                    result.put("balanceFormatted",    info.getBalanceFormatted());
                    result.put("monthlyPremiumCents", info.monthlyPremiumCents());
                    result.put("monthlyPremiumFormatted", info.getMonthlyPremiumFormatted());
                    result.put("additionalInfo",      nullSafe(info.additionalInfo()));
                    result.put("currency",            info.currency());
                    result.put("policyStatus",        nullSafe(info.policyStatus()));
                    result.put("isPolicyActive",      info.isPolicyActive());
                    result.put("merchantCode",        "NYARADZO");
                    break;
                }
                case "MOONLIGHT": {
                    MoonlightAdaptor.MoonlightCustomerInfo info =
                            moonlightAdaptor.getCustomerInfo(accountNumber.trim(), sourcePhone);
                    result = new LinkedHashMap<>();
                    result.put("holderName",     nullSafe(info.holderName()));
                    result.put("policyNumber",   info.policyNumber());
                    result.put("additionalInfo", nullSafe(info.additionalInfo()));
                    result.put("merchantCode",   "MOONLIGHT");
                    break;
                }
                default:
                    throw new IllegalArgumentException("Unknown merchant: " + merchantCode);
            }

            return ResponseEntity.ok(ApiResponse.success(result, traceId));

        } catch (IllegalArgumentException e) {
            return badRequest(e.getMessage(), traceId);
        } catch (Exception e) {
            log.error("[BillCustomerInfo] Error: {}", e.getMessage(), e);
            return ResponseEntity.internalServerError()
                    .body(ApiResponse.error("LOOKUP_FAILED", e.getMessage(), traceId));
        }
    }

    private ResponseEntity<ApiResponse<Map<String, Object>>> badRequest(String message, String traceId) {
        return ResponseEntity.badRequest()
                .body(ApiResponse.error("VALIDATION_ERROR", message, traceId));
    }

    private String upper(String s) { return s != null ? s.toUpperCase().trim() : null; }
    private String nullSafe(String s) { return s != null ? s : ""; }
}