package zw.co.payport.gateway.entity;

import jakarta.persistence.*;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.AllArgsConstructor;
import lombok.Builder;
import zw.co.payport.gateway.enums.TransactionChannel;
import zw.co.payport.gateway.enums.TransactionStatus;

import java.time.LocalDateTime;

/**
 * Core transaction entity.
 * IMPORTANT: amount_cents is BIGINT - ALL monetary values stored as integer cents.
 * $5.00 = 500 cents. NEVER use double/float for money.
 */
@Data
@Entity
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Table(name = "transactions", indexes = {
        @Index(name = "idx_tx_reference",     columnList = "reference",          unique = true),
        @Index(name = "idx_tx_status",        columnList = "status,created_at"),
        @Index(name = "idx_tx_customer",      columnList = "customer_phone"),
        @Index(name = "idx_tx_recipient",     columnList = "recipient_identifier"),
        @Index(name = "idx_tx_created",       columnList = "created_at")
})
public class Transaction {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // ── Reference ────────────────────────────────────────────────
    // PP-{CHANNEL}-{YYYYMMDD}-{SEQ6}  e.g. PP-WEB-20260315-000042
    // NEVER generated by the gateway - always client-provided and validated
    @Column(nullable = false, unique = true, length = 24)
    private String reference;

    // ── State Machine ─────────────────────────────────────────────
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private TransactionStatus status;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private TransactionChannel channel;

    // ── Product ───────────────────────────────────────────────────
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "product_type_id", nullable = false)
    private ProductType productType;

    // ── Payment ───────────────────────────────────────────────────
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "payment_method_id")
    private PaymentMethod paymentMethod;

    // ── Parties ───────────────────────────────────────────────────
    @Column(length = 20)
    private String customerPhone;          // who is paying

    @Column(nullable = false, length = 100)
    private String recipientIdentifier;    // who receives (phone, meter number, account)

    // ── Money (ALWAYS CENTS - NEVER DECIMAL) ─────────────────────
    @Column(nullable = false)
    private Long amountCents;              // $5.00 → 500L

    @Column(nullable = false, length = 3, columnDefinition = "VARCHAR(3)")
    private String currency;

    // ── User association (optional — guests allowed) ──────────────
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id")
    private User user;

    // ── Payment Provider Full Details ─────────────────────────────
    @Column(length = 50)
    private String paymentProviderCode;

    @Column(length = 200)
    private String providerReference;           // payment provider's own reference (from callback)

    @Column(length = 200)
    private String paymentCorrelator;           // clientCorrelator sent to EcoCash / OneMoney

    @Column(length = 200)
    private String paymentProviderTxId;         // Provider's internal transaction ID

    @Column(length = 100)
    private String paymentProviderStatus;       // Raw status from provider (PENDING SUBSCRIBER VALIDATION etc)

    @Column(length = 500)
    private String paymentProviderMessage;      // Provider message/description

    @Column(columnDefinition = "TEXT")
    private String paymentProviderRawResponse;  // Full raw JSON from provider

    @Column
    private Long paymentConfirmedAmountCents;   // Amount confirmed by provider

    @Column(length = 3, columnDefinition = "VARCHAR(3)")
    private String paymentConfirmedCurrency;

    // ── Fulfilment Provider Full Details ──────────────────────────
    @Column(length = 200)
    private String fulfilmentReference;         // service provider's delivery reference

    @Column(columnDefinition = "TEXT")
    private String fulfilmentData;              // extra delivery data as JSON (e.g. ZESA token)

    @Column(length = 50)
    private String fulfilmentProviderCode;

    @Column(columnDefinition = "TEXT")
    private String fulfilmentProviderRawResponse;

    @Column(length = 100)
    private String fulfilmentProviderStatus;

    // ── Customer Enrichment ───────────────────────────────────────
    @Column(length = 200)
    private String customerName;               // if registered user

    @Column(length = 200)
    private String customerEmail;              // optional

    @Column(length = 20)
    private String recipientNetwork;           // ECONET | NETONE | TELECEL

    @Column(length = 200)
    private String recipientName;              // for bill payments - account name

    @Column(length = 200)
    private String productName;                // snapshot at time of tx

    @Column(length = 100)
    private String paymentMethodName;          // snapshot at time of tx

    // ── Meta ──────────────────────────────────────────────────────
    @Column(length = 45)
    private String ipAddress;

    @Column(length = 500)
    private String userAgent;

    @Column(length = 50)
    private String deviceType;                 // WEB | MOBILE | API

    @Column(length = 100)
    private String sessionId;

    @Column(columnDefinition = "TEXT")
    private String notes;                      // Internal ops notes

    @Column(length = 100)
    private String opsAssignedTo;

    @Column(nullable = false)
    private Integer retryCount;

    @Column(length = 2000)
    private String failureReason;

    // ── Additional failure details for better error display ───────
    @Column(columnDefinition = "TEXT")
    private String failureDetails;

    // ── Manual refund details (ops entering a reference for a refund done
    //    outside the system — bank transfer, EcoCash, OneMoney, Innbucks,
    //    Omari — not an automatic provider-side reversal) ───────────────
    private String refundReference;
    private String refundMethod;
    private LocalDateTime refundedAt;

    /**
     * Omari-confirmed policy: customer gets up to 3 OTP attempts, and
     * Omari themselves enforce the 5-minute validity window -- Payport
     * deliberately doesn't run its own timer for that; a call after the
     * code has expired just comes back as another Omari error, handled
     * the same as any other wrong attempt.
     */
    private Integer omariOtpAttempts;

    // ── Timestamps ────────────────────────────────────────────────
    @Column(nullable = false)
    private LocalDateTime initiatedAt;

    private LocalDateTime paymentSubmittedAt;
    private LocalDateTime paymentConfirmedAt;
    private LocalDateTime fulfilmentStartedAt;
    private LocalDateTime completedAt;
    private LocalDateTime failedAt;

    @Column(nullable = false)
    private LocalDateTime createdAt;

    @Column(nullable = false)
    private LocalDateTime updatedAt;

    // ── Lifecycle hooks ───────────────────────────────────────────
    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        createdAt  = now;
        updatedAt  = now;
        initiatedAt = now;
        if (status == null)     status     = TransactionStatus.INITIATED;
        if (currency == null)   currency   = "USD";
        if (retryCount == null) retryCount = 0;
        if (channel == null)    channel    = TransactionChannel.WEB;
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }

    // ── Helpers ───────────────────────────────────────────────────
    public double getAmountAsDouble() {
        return amountCents != null ? amountCents / 100.0 : 0.0;
    }

    public String getAmountFormatted() {
        return String.format("$%.2f", getAmountAsDouble());
    }
}